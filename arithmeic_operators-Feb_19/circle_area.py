# ==========================================================
# This program calculates the area of a Circle
# Formula:
# Area = π × r²
# π (pi) ≈ 3.14159
# ==========================================================
# Taking radius as input
radius = float(input("Enter radius of circle: "))

# Calculating area using formula
area = 3.14159 * radius * radius

# Displaying result
print("Area of Circle:", area)